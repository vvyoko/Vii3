-- @name     焦点虚化
-- @author   vii3
-- @desc     焦点内清晰、越远越糊（焦点跟指针）
-- @version  2.0
-- @builtin  no
-- @needs    pointer
-- @oneshot  yes
-- @param    radius  0.16 0.05 0.5 清晰半径（按原图短边归一）
-- @param    feather 0.10 0.02 0.5 过渡宽度（越大过渡越柔）
--
-- 参数：外部可调（命令 "设置特效"，参数串写法见 api.md 1.4）——
--   例："focus_blur radius +0.02; feather 0.12"（按住快捷键把清晰圈一点点放大）。
--
-- 2.0 起改用 focusBlur 构造器：
--   模糊交给原生 CreateBlur（整图糊一次，分离卷积，σ 再大也不贵），
--   SkSL 只做"按距离混清晰版 / 模糊版"（无采样循环）——1.0 那版是手搓 24 次螺旋采样，半径大就看得出噪点。
--
-- 焦点从哪来（"脚本声明、运行时替换"）：
--   · 脚本只声明 uniform：uFocus（指针位置，图像归一化 0..1）+ uPointer（有没有指针）
--   · 引擎在绘制时填真值：调用那一刻的鼠标位置（快捷键按下时快照）⇒ 焦点就在鼠标处
--   · 没指针（事件被吞 / 从菜单调用）⇒ uPointer = 0 ⇒ 落回下面的默认焦点 (0.5, 0.45)
--
-- 参数：
--   sigma   模糊 σ（原图像素）：越大越糊，12~20 是"背景虚化"的常见量
--   radius  清晰半径（按原图短边归一）：0.16 ≈ 中心 16% 保持清晰
--   feather 过渡宽度（同样归一）：越大过渡越柔
return {
  { focusBlur = { sigma = 14, radius = 0.16, feather = 0.10 } },
}
